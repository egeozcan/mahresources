test('random result pages and Mass Edit share the executed sample', async ({page,apiClient,request}) => {
    const prefix = `review-random-${Date.now()}`;
    const type = await apiClient.createNoteType(prefix);
    await apiClient.createTag(prefix);
    for (let i=0;i<9;i++) await apiClient.createNote({name:`${prefix} ${i}`,noteTypeId:type.ID});
    const mrql = new MRQLPage(page);
    await mrql.navigate();
    await mrql.enterQuery(`type = note AND name ~ "${prefix}" ORDER BY RANDOM() LIMIT 7`);
    await mrql.executeQuery();
    await page.getByLabel('Per page',{exact:false}).selectOption('5');
    const notes = page.locator('[data-selection-scope="mrql-note"]');
    await expect(notes.locator('.note-card')).toHaveCount(5);
    const names = await notes.locator('.card-title').allTextContents();
    await page.getByRole('button',{name:'Next',exact:true}).click();
    await expect(notes.locator('.note-card')).toHaveCount(2);
    names.push(...await notes.locator('.card-title').allTextContents());
    expect(new Set(names.map(name=>name.trim())).size).toBe(7);
    await notes.getByRole('button',{name:'Mass edit all results',exact:true}).click();
    const dialog=page.getByRole('dialog',{name:'Mass edit notes',exact:true});
    await dialog.getByRole('combobox',{name:'Tags to apply',exact:true}).fill(prefix);
    await page.getByRole('option').filter({hasText:prefix}).first().click();
    await dialog.getByRole('button',{name:'Apply',exact:true}).click();
    const confirmation=page.getByRole('alertdialog',{name:'Mass edit',exact:true});
    await expect(confirmation).toContainText('7 notes');
    await confirmation.getByRole('button',{name:'Apply',exact:true}).click();
    await expect(dialog).not.toBeVisible();
    const response = await request.post('/v1/mrql',{data:{query:`type = note AND tags = "${prefix}"`}});
    const result = await response.json();
    expect(result.notes.map((note:{Name:string})=>note.Name).sort()).toEqual(names.map(name=>name.trim()).sort());
});
