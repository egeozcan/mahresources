test('MRQL paging retains keyboard focus, including at the first and last pages', async ({page,apiClient}) => {
    const prefix = `shared-focus-${Date.now()}`;
    const noteType = await apiClient.createNoteType(prefix);
    for (let i = 0; i < 11; i++) await apiClient.createNote({name:`${prefix} ${i}`,noteTypeId:noteType.ID});
    const mrql = new MRQLPage(page);
    await mrql.navigate();
    await mrql.enterQuery(`type = note AND name ~ "${prefix}" ORDER BY name ASC LIMIT 11`);
    await mrql.executeQuery();
    const size = page.getByLabel('Per page', {exact:false});
    await size.focus();
    await size.selectOption('5');
    await expect(page.locator('.note-card')).toHaveCount(5);
    await expect(size).toBeFocused();
    const next = page.getByRole('button', {name:'Next',exact:true});
    const previous = page.getByRole('button', {name:'Previous',exact:true});
    const status = page.locator('[data-mrql-page-status]');
    await next.focus();
    await next.press('Enter');
    await expect(status).toContainText('Page 2');
    await expect(next).toBeFocused();
    await next.press('Enter');
    await expect(status).toContainText('Page 3');
    await expect(status).toBeFocused();
    await previous.focus();
    await previous.press('Enter');
    await expect(status).toContainText('Page 2');
    await expect(previous).toBeFocused();
    await previous.press('Enter');
    await expect(status).toContainText('Page 1');
    await expect(status).toBeFocused();
});

